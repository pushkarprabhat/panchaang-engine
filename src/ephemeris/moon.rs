use super::{centuries_j2000, normalize_deg};

/// Ecliptic longitude of the Moon, degrees (Meeus ch.47, principal terms).
pub fn moon_ecliptic_long(jd: f64) -> f64 {
    let t = centuries_j2000(jd);
    let lp = normalize_deg(218.3164477 + 481267.88123421 * t - 0.0015786 * t * t);
    let d = normalize_deg(297.8501921 + 445267.1114034 * t - 0.0018819 * t * t);
    let m = normalize_deg(357.5291092 + 35999.0502909 * t - 0.0001536 * t * t);
    let mp = normalize_deg(134.9633964 + 477198.8675055 * t + 0.0087414 * t * t);
    let f = normalize_deg(93.2720950 + 483202.0175233 * t - 0.0036539 * t * t);

    let d2r = |x: f64| x.to_radians();
    let (d, m, mp, f) = (d2r(d), d2r(m), d2r(mp), d2r(f));

    let mut sum = 0.0;
    let terms = [
        (6.288774, 0.0, 0.0, 1.0, 0.0),
        (1.274027, 2.0, 0.0, -1.0, 0.0),
        (0.658314, 2.0, 0.0, 0.0, 0.0),
        (0.213618, 0.0, 0.0, 2.0, 0.0),
        (-0.185116, 0.0, 1.0, 0.0, 0.0),
        (-0.114332, 0.0, 0.0, 0.0, 2.0),
        (0.058793, 2.0, 0.0, -2.0, 0.0),
        (0.057066, 2.0, -1.0, -1.0, 0.0),
        (0.053322, 2.0, 0.0, 1.0, 0.0),
        (0.045758, 2.0, -1.0, 0.0, 0.0),
        (0.040986, 0.0, 1.0, -1.0, 0.0),
        (0.034720, 1.0, 0.0, 0.0, 0.0),
        (-0.030383, 0.0, 1.0, 1.0, 0.0),
        (0.015327, 2.0, 0.0, 0.0, -2.0),
        (-0.012528, 0.0, 0.0, 1.0, 2.0),
        (0.010980, 0.0, 0.0, 1.0, -2.0),
        (0.010674, 4.0, 0.0, -1.0, 0.0),
        (0.010034, 0.0, 0.0, 3.0, 0.0),
        (0.008548, 4.0, 0.0, -2.0, 0.0),
        (-0.007888, 2.0, 1.0, -1.0, 0.0),
        (-0.006783, 2.0, 1.0, 0.0, 0.0),
        (0.005162, 0.0, 0.0, -1.0, 0.0),
        (0.005000, 1.0, 0.0, 1.0, 0.0),
        (0.004049, 2.0, -1.0, 1.0, 0.0),
        (0.003996, 2.0, 0.0, 2.0, 0.0),
        (0.003862, 4.0, 0.0, 0.0, 0.0),
    ];
    for (c, ad, bm, cmp, df) in terms {
        sum += c * (ad * d + bm * m + cmp * mp + df * f).sin();
    }
    normalize_deg(lp + sum)
}
